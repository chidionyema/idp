"""mkdocs hook: surface every Forge experiment in Backstage (crew#885; founder 2026-09-06: "all need
to be in backstage").

At each docs build, copies `forge/experiments/*.md` (pre-registrations and run records) to
`docs/reference/forge/` and writes an `index.md` there: one row per file, plain English first
(task, what happened, when), the numbers beside it. The copies are generated, never committed
(.gitignore), so they cannot go stale the way a committed register did (crew#679 CP2). Wired in
mkdocs.yml `hooks:`; the CI docs rung (`bin/idp-ci` 8c, `mkdocs build --strict`) proves it.
"""

from __future__ import annotations

import shutil
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "forge" / "experiments"
OUT = ROOT / "docs" / "reference" / "forge"


def front_matter(text: str) -> dict:
    if not text.startswith("---\n"):
        return {}
    end = text.find("\n---", 4)
    if end < 0:
        return {}
    try:
        return yaml.safe_load(text[4:end]) or {}
    except yaml.YAMLError:
        return {}


def one_line(text: str) -> str:
    """The first paragraph under '## In plain English', if the file has one."""
    marker = "## In plain English"
    at = text.find(marker)
    if at < 0:
        return ""
    body = text[at + len(marker) :].strip()
    para = body.split("\n\n", 1)[0]
    return " ".join(para.split())


def pct(v) -> str:
    return "" if v is None else f"{float(v):.0%}"


def render_index(records: list[tuple[str, dict, str]]) -> str:
    lines = [
        "# Own models: every Forge experiment",
        "",
        "Each row is one file under `forge/experiments/`: a plan written before a run, or the record a",
        "run left. Plain English first; the numbers are the same ones the run was graded against.",
        "Records are generated by `forge/experiment_record.py`; nobody writes one by hand except a plan.",
        "",
        "| experiment | task | what happened | agreement | abstained | cost (USD) |",
        "|---|---|---|---|---|---|",
    ]
    for name, fm, plain in records:
        status = fm.get("verdict") or fm.get("status") or ""
        what = plain or status
        lines.append(
            f"| [{name}]({name}.md) | {fm.get('task', '')} | {what} | "
            f"{pct(fm.get('agreement'))} | {pct(fm.get('abstain_rate'))} | {fm.get('usd', '')} |"
        )
    lines += [
        "",
        "How to read a record and what a task may try: [the Forge experiments README](README.md).",
        "",
    ]
    return "\n".join(lines)


def write_pages() -> Path:
    OUT.mkdir(parents=True, exist_ok=True)
    for stale in OUT.glob("*.md"):
        stale.unlink()
    records = []
    for src in sorted(SRC.glob("*.md")):
        shutil.copyfile(src, OUT / src.name)
        if src.name == "README.md":
            continue
        text = src.read_text(encoding="utf-8")
        records.append((src.stem, front_matter(text), one_line(text)))
    (OUT / "index.md").write_text(render_index(records), encoding="utf-8")
    return OUT


def on_pre_build(config, **kwargs) -> None:  # noqa: ARG001 - mkdocs hook signature
    out = write_pages()
    print(f"forge-experiments: wrote {out.relative_to(ROOT)}")
