"""The Pod a workload controller would create, so an offline judge sees what admission sees.

Kyverno judges a Deployment with the autogenerated copy of a rule (`autogen-validate-probes`) and
the Pod its ReplicaSet then creates with the original (`validate-probes`). Both fire on the
cluster. Offline, only the Deployment was ever handed to the CLI, so a PolicyException that
excused the autogen rule and not the original read as a clean render and was refused at admission.

2026-08-30, run 33335791923: `bin/idp-kyverno-render platform/tailscale` printed
`ok render tailscale-operator ... fail: 0` while the cluster was printing

    resource Pod/tailscale/operator-56cf79864d-hjdcg was blocked due to the following policies
    require-pod-probes:
      validate-probes: 'validation failure: Liveness, readiness, or startup probes are required'

for the same object, because platform/edge/tailscale-operator-exception.yaml named the policy
`require-pod-probes` in its `ruleNames` where the rule `validate-probes` belonged. tailscale,
Guacamole and Temporal were down behind it, and the judge said the render was clean.

The estate had already met one half of this: crew#284 (2026-08-25) found that autogen does not
cover Job or CronJob, and a migrator Job whose Pod admission refused had passed here. The Pod was
synthesised for those two kinds only. Autogen covering a kind is what made the other three look
safe -- it covers the policy, never the exception.
"""

# The controller that owns the Pod admission sees. A Deployment's Pod is owned by its ReplicaSet
# and a CronJob's by the Job it created, so neither names the workload in the ownerReference: a
# policy or exception matching on the owner has to see the same chain the cluster builds.
_OWNER = {
    "Deployment": ("apps/v1", "ReplicaSet", "{name}-offline"),
    "StatefulSet": ("apps/v1", "StatefulSet", "{name}"),
    "DaemonSet": ("apps/v1", "DaemonSet", "{name}"),
    "Job": ("batch/v1", "Job", "{name}"),
    "CronJob": ("batch/v1", "Job", "{name}-offline"),
}


def _template(doc):
    """The pod template a controller stamps out, or None for anything that stamps out no pods."""
    kind = doc.get("kind")
    if kind == "CronJob":
        return (
            ((doc.get("spec") or {}).get("jobTemplate") or {})
            .get("spec", {})
            .get("template")
        )
    if kind in _OWNER:
        return (doc.get("spec") or {}).get("template")
    return None


def pods_for(docs):
    """Every Pod the given workloads would create, named the way admission would name it.

    The name carries the workload's own name as its prefix because that is what an exception
    matches on: the cluster's `operator-56cf79864d-hjdcg` and this `operator-pod` are both caught
    by `names: [operator*]`, and an exception naming a bare `operator` matches neither -- which is
    a real refusal at admission, so it is right that it is a refusal here too.
    """
    out = []
    for d in docs:
        tpl = _template(d)
        if not tpl:
            continue
        meta = d.get("metadata") or {}
        api, kind, owner = _OWNER[d["kind"]]
        out.append(
            {
                "apiVersion": "v1",
                "kind": "Pod",
                "metadata": {
                    "name": meta.get("name", "") + "-pod",
                    "namespace": meta.get("namespace"),
                    "labels": (tpl.get("metadata") or {}).get("labels") or {},
                    "annotations": (tpl.get("metadata") or {}).get("annotations") or {},
                    "ownerReferences": [
                        {
                            "apiVersion": api,
                            "kind": kind,
                            "name": owner.format(name=meta.get("name", "")),
                            "uid": "offline",
                        }
                    ],
                },
                "spec": tpl["spec"],
            }
        )
    return out
