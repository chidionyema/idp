"""The method catalogue (SF-1): what the estate knows how to reach for, and when.

Every entry carries the things the founder's operational contract demands of an addition:
a reference, the problem kinds it applies to, its prerequisites, its anti-patterns, its
cost profile, its risk, the evidence it is expected to produce, its stop and switch
conditions, and the independent verifier that would judge its output.

Two rules are load-bearing:

* **A catalogue entry is a claim about applicability, never a claim of proof.** Every entry
  is `evaluation_status = UNVERIFIED` until the fixture suite and the independent evaluator
  land (the spec's SF-3). The selector is therefore allowed to *recommend* any of these and
  forbidden to call any of them proven.
* **The catalogue never executes anything.** It is data: prerequisites, costs, conditions.
  Execution belongs to the estate's governed executor and verification belongs to the
  independent verifier, both of which already exist.
"""

