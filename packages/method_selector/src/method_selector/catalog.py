@dataclass(frozen=True)
class MethodSpec:
    """One method, fully described. Immutable.

    `max_attempts` is the method's documented worst case; `typical_attempts` is its expected
    cost in attempts and is what a caller's attempt ceiling is compared against - a bisect
    that may need twenty steps is still the right method for a caller who allows twelve,
    because the ceiling bounds the run, it does not disqualify the method.
    """

    method_id: str
    version: str
    family: str
    title: str
    problem_kinds: Tuple[str, ...]
    prerequisites: Tuple[str, ...]
    disqualifying_kinds: Tuple[str, ...]
    anti_patterns: Tuple[str, ...]
    cost_per_attempt_usd: float
    max_attempts: int
    typical_attempts: int
    risk: str
    requires_authorization: bool
    tool_scopes: Tuple[str, ...]
    expected_evidence: Tuple[str, ...]
    stop_conditions: Tuple[str, ...]
    switch_conditions: Tuple[str, ...]
    verifier: str
    references: Tuple[str, ...]
    baseline_priority: int

    def to_dict(self) -> Dict[str, object]:
        return {
            "method_id": self.method_id,
            "version": self.version,
            "family": self.family,
            "title": self.title,
            "problem_kinds": list(self.problem_kinds),
            "prerequisites": list(self.prerequisites),
            "anti_patterns": list(self.anti_patterns),
            "cost_per_attempt_usd": self.cost_per_attempt_usd,
            "max_attempts": self.max_attempts,
            "typical_attempts": self.typical_attempts,
            "risk": self.risk,
            "requires_authorization": self.requires_authorization,
            "tool_scopes": list(self.tool_scopes),
            "expected_evidence": list(self.expected_evidence),
            "stop_conditions": list(self.stop_conditions),
            "switch_conditions": list(self.switch_conditions),
            "verifier": self.verifier,
            "references": list(self.references),
            "baseline_priority": self.baseline_priority,
            "evaluation_status": "UNVERIFIED",
        }


def _spec(
    method_id: str,
    version: str,
    family: str,
    title: str,
    problem_kinds: Tuple[str, ...],
    prerequisites: Tuple[str, ...],
    disqualifying_kinds: Tuple[str, ...],
    anti_patterns: Tuple[str, ...],
    cost_per_attempt_usd: float,
    max_attempts: int,
    risk: str,
    requires_authorization: bool,
    tool_scopes: Tuple[str, ...],
    expected_evidence: Tuple[str, ...],
    stop_conditions: Tuple[str, ...],
    switch_conditions: Tuple[str, ...],
    verifier: str,
    references: Tuple[str, ...],
    baseline_priority: int,
    typical_attempts: Optional[int] = None,
) -> MethodSpec:
    return MethodSpec(
        method_id=method_id,
        version=version,
        family=family,
        title=title,
        problem_kinds=problem_kinds,
        prerequisites=prerequisites,
        disqualifying_kinds=disqualifying_kinds,
        anti_patterns=anti_patterns,
        cost_per_attempt_usd=cost_per_attempt_usd,
        max_attempts=max_attempts,
        typical_attempts=(
            typical_attempts
            if typical_attempts is not None
            else max(1, int(round(max_attempts / 3.0)))
        ),
        risk=risk,
        requires_authorization=requires_authorization,
        tool_scopes=tool_scopes,
        expected_evidence=expected_evidence,
        stop_conditions=stop_conditions,
        switch_conditions=switch_conditions,
        verifier=verifier,
        references=references,
        baseline_priority=baseline_priority,
    )


