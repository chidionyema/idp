"""Machine-generated receipts: the only currency a report to the founder is allowed to spend.

THE FOUNDER'S RULE (2026-10-29): "period i do not want anybody telling me anything i can't
verify on the spot and see the machine generated receipts" and "need verifiable, machine
generated proof ... block everyone from reporting to founder without this".

A receipt is one command, its exit status, the line it printed, and a sha256 of its output:

    {"ts": "2026-10-29T22:51:03Z", "command": ["bin/idp-ci"], "cwd": "...",
     "exit": 0, "line": "ok  gate: 42 checks passed", "sha256": "9f2c...",
     "stdout_tail": "...", "stderr_tail": ""}

Two properties make it worth anything:

  * it is generated by the machine, never typed by an agent;
  * it can be re-verified on the spot: `bin/estate-receipt --verify <receipt.json>` re-runs
    the command and compares the exit status and the sha256.

Everything that wants to report to the founder goes through `format_receipt`, and the report
gate (the pi extension's turn-end check) refuses a report that carries no receipt.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import subprocess
import time
from typing import Any, Dict, List, Optional, Tuple

TAIL = 400


def _tail(text: str) -> str:
    text = text or ""
    if len(text) <= TAIL:
        return text
    return "..." + text[-TAIL:]


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def run_receipt(
    argv: List[str],
    cwd: Optional[str] = None,
    timeout: float = 120.0,
    env: Optional[Dict[str, str]] = None,
) -> Dict[str, Any]:
    """Run a command and mint a receipt for it. Never raises: a failed command is a receipt
    with a non-zero exit, because "it failed" is exactly what the founder needs to see."""
    started = time.time()
    run_env = dict(os.environ)
    if env:
        run_env.update(env)
    try:
        proc = subprocess.run(  # noqa: S603 - argv is data, never a shell string
            argv,
            cwd=cwd,
            capture_output=True,
            text=True,
            timeout=timeout,
            env=run_env,
        )
        out, err, code = proc.stdout, proc.stderr, proc.returncode
    except subprocess.TimeoutExpired:
        out, err, code = "", f"timeout after {timeout}s", 124
    except OSError as exc:
        out, err, code = "", f"{type(exc).__name__}: {exc}", 127
    lines = [ln for ln in (out or "").splitlines() if ln.strip()]
    line = (
        lines[-1]
        if lines
        else (err or "").splitlines()[-1]
        if (err or "").strip()
        else ""
    )
    return {
        "ts": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "command": list(argv),
        "cwd": cwd or os.getcwd(),
        "exit": code,
        "line": line,
        "sha256": sha256(((out or "") + (err or "")).encode()),
        "stdout_tail": _tail(out),
        "stderr_tail": _tail(err),
        "duration_s": round(time.time() - started, 3),
    }


def verify(receipt: Dict[str, Any]) -> Dict[str, Any]:
    """Re-run the receipt's command and compare exit status and output hash."""
    argv = receipt.get("command") or []
    if not argv:
        return {"ok": False, "reason": "receipt carries no command"}
    fresh = run_receipt(argv, cwd=receipt.get("cwd"))
    ok = fresh["exit"] == receipt.get("exit") and fresh["sha256"] == receipt.get(
        "sha256"
    )
    return {"ok": ok, "receipt": receipt, "fresh": fresh}


def format_receipt(receipt: Dict[str, Any]) -> str:
    """The block an agent pastes into a report: command, exit status, line, hash."""
    return (
        f"$ {' '.join(receipt.get('command') or [])}\n"
        f"exit: {receipt.get('exit')}\n"
        f"line: {receipt.get('line')}\n"
        f"sha256: {receipt.get('sha256')}"
    )


def save(receipt: Dict[str, Any], path: str) -> str:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        json.dump(receipt, f, indent=2, sort_keys=True)
    return path


# A receipt is a machine-printed shape, not a word. The founder's relayed directive
# (2026-10-30, estate-fleet broadcast seq=2): "no receipt keyword or self-typed success is
# proof". So the check looks for the four labels the machine prints -- the command, the exit
# status, the line it printed and the sha256 of its output -- and nothing else. The word
# "receipt" in prose, a path to a receipt file, or a sentence saying it worked are refused.
_CMD_RE = re.compile(r"(?m)^\s*\$\s+(\S.*?)\s*$")
_EXIT_RE = re.compile(r"(?m)^\s*exit(?:\s+code|\s+status)?\s*[:=]\s*(-?\d+)\s*$")
_LINE_RE = re.compile(r"(?m)^\s*line\s*[:=]\s*(\S.*?)\s*$")
_SHA256_RE = re.compile(r"(?m)^\s*sha256\s*[:=]\s*([0-9a-fA-F]{64})\s*$")


def _json_receipts(text: str) -> List[Dict[str, Any]]:
    """Every JSON object in the text that is a receipt in its own right."""
    found: List[Dict[str, Any]] = []
    for start, char in enumerate(text):
        if char != "{":
            continue
        depth = 0
        for end in range(start, len(text)):
            if text[end] == "{":
                depth += 1
            elif text[end] == "}":
                depth -= 1
                if depth == 0:
                    try:
                        obj = json.loads(text[start : end + 1])
                    except ValueError:
                        break
                    if isinstance(obj, dict):
                        found.append(obj)
                    break
    return found


def _is_json_receipt(obj: Dict[str, Any]) -> bool:
    digest = obj.get("sha256")
    if not isinstance(digest, str) or not re.fullmatch(r"[0-9a-fA-F]{64}", digest):
        return False
    if not isinstance(obj.get("exit"), int):
        return False
    if not isinstance(obj.get("command"), list) or not obj["command"]:
        return False
    if not isinstance(obj.get("line"), str):
        return False
    return True


def receipt_reason(text: str) -> Tuple[bool, str]:
    """Is this report carrying machine-generated proof, and if not, what is missing?

    Accepts the machine's own block (a `$` command line, an exit status, the line it printed
    and the sha256 of its output) or a receipt object embedded as JSON. Anything else --
    narration, the bare word "receipt", a path to a receipt file -- is refused, and the
    refusal names what is missing so the author can fix it instead of guessing.
    """
    if not text or not text.strip():
        return False, "the report is empty"
    for obj in _json_receipts(text):
        if _is_json_receipt(obj):
            return True, "receipt object found"
    missing = []
    if not _CMD_RE.search(text):
        missing.append("the command line ($ ...)")
    if not _EXIT_RE.search(text):
        missing.append("the exit status (exit: N)")
    if not _LINE_RE.search(text):
        missing.append("the line it printed (line: ...)")
    if not _SHA256_RE.search(text):
        missing.append("the sha256 of its output (sha256: <64 hex>)")
    if missing:
        return False, "not machine-generated proof: missing " + ", ".join(missing)
    return True, "machine-generated receipt found"


def has_receipt(text: str) -> bool:
    """Does this report carry machine-generated proof?

    The answer is a strict shape check, never a keyword search: a keyword is exactly what an
    agent writes when it wants to look like it proved something."""
    return receipt_reason(text)[0]
