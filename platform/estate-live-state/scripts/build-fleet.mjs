#!/usr/bin/env node
// Builds src/fleet-page.mjs: the web reader, as ONE string the worker serves at /fleet.
// The page does not re-implement the fold, the hash or the read. It inlines the very sources the
// terminal runs (src/fold.mjs and scripts/watch-lib.mjs), so a reader cannot drift from the others.
// The committed output is checked against a fresh build by test/fleet.test.mjs.
//   node scripts/build-fleet.mjs          writes src/fleet-page.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));

/** The inline script: the shared sources with imports and `export` removed, then the view. */
export function pageScript(fold, watch) {
  const strip = (src) => src.replace(/^import .*;\n/gm, "").replace(/^export /gm, "");
  return `${strip(fold)}\n${strip(watch)}
const $ = (id) => document.getElementById(id);
const keep = (k, v) => { try { v === null ? sessionStorage.removeItem(k) : sessionStorage.setItem(k, v); } catch {} };
const held = (k) => { try { return sessionStorage.getItem(k); } catch { return null; } };
async function tick() {
  const r = await watch({ base: location.origin, token: held("t") });
  const ok = r.code === 0;
  // a read that did not happen shows BLIND and no numbers; the last good state is never kept
  $("board").textContent = ok ? r.out.join("\\n") : ["BLIND  estate-live-state", ...r.out, ...r.err].join("\\n");
  $("board").className = ok ? "ok" : "blind";
}
$("token").addEventListener("change", (e) => { keep("t", e.target.value || null); e.target.value = ""; tick(); });
tick();
setInterval(tick, 2000);`;
}

export function buildPage(fold, watch) {
  const script = pageScript(fold, watch);
  if (script.includes("</script")) throw new Error("the inlined sources contain </script");
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Estate live state</title>
<style>:root{color-scheme:light dark}body{margin:16px;font:14px/1.4 ui-monospace,monospace}pre{white-space:pre-wrap;overflow-wrap:anywhere}.blind{color:#b00020}.ok{color:inherit}</style>
</head><body>
<h1>Estate live state</h1>
<input id="token" type="password" placeholder="read token (kept for this tab only)" autocomplete="off">
<pre id="board" class="blind">BLIND  estate-live-state\nnot read yet</pre>
<script>
${script}
</script>
</body></html>
`;
}

export function moduleSource(page) {
  return `// GENERATED by scripts/build-fleet.mjs from src/fold.mjs and scripts/watch-lib.mjs. Do not edit.\nexport const PAGE = ${JSON.stringify(page)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const page = buildPage(readFileSync(here("../src/fold.mjs"), "utf8"), readFileSync(here("./watch-lib.mjs"), "utf8"));
  writeFileSync(here("../src/fleet-page.mjs"), moduleSource(page));
  console.log(`wrote src/fleet-page.mjs (${page.length} chars)`);
}
