#!/usr/bin/env node
// Make every router lane selectable in Codex (CLI and desktop) from the one lane table.
//
// Codex 0.169 speaks only the Responses API; the Worker serves it at /v1/responses (see
// src/responses_adapter.mjs). What Codex still needs is (1) a provider that points at the
// Worker and fetches its bearer from the vault by NAME, and (2) a model catalog with one entry
// per lane, because a custom provider's models do not exist in Codex's own catalog.
//
// Codex 0.169 refuses `[profiles.*]` inside config.toml ("legacy ... move those settings into
// <profile>.config.toml", measured), so the router is its own file, `meridian.config.toml`,
// selected with `codex --profile meridian`. The user's config.toml is never edited. The
// profile never takes over the default provider: AGENTS.md section 7a keeps the ChatGPT login
// as the Codex default. The file is wholly generated, so re-running rewrites it to the same bytes.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { rolePool } from "./role-pool.mjs";

export const PROVIDER = "meridian";
export const DEFAULT_BASE_URL = "https://llm.meridianlabs.cloud/v1";
export const KEY_NAME = "MERIDIAN_CLIENT_KEY";

/** One catalog entry per enabled lane, cloned from a template entry Codex itself wrote. */
export function codexCatalog(template, lanes) {
  if (!template || typeof template.slug !== "string" || !template.base_instructions) {
    throw new Error("template must be a full Codex model entry (slug + base_instructions)");
  }
  if (!lanes.length) throw new Error("no lane to publish");
  const models = lanes.map((lane, i) => ({
    ...structuredClone(template),
    slug: lane.id,
    display_name: lane.id,
    description: `${lane.vendor} lane on the Meridian router (text only: tools are not forwarded).`,
    context_window: lane.maxContextTokens,
    max_context_window: lane.maxContextTokens,
    supports_parallel_tool_calls: false,
    supports_search_tool: false,
    visibility: "list",
    priority: i + 1,
  }));
  return { models };
}

export function profileToml({ catalogPath, baseUrl = DEFAULT_BASE_URL, keyCommand, keyArgs, defaultModel }) {
  if (!keyCommand || !Array.isArray(keyArgs)) throw new Error("a key command and args are required");
  const q = (s) => JSON.stringify(s);
  // Top-level keys first: after a table header they would belong to that table.
  return [
    "# Generated by platform/router-edge/scripts/codex-profile.mjs. Do not edit: re-run it.",
    `model_provider = ${q(PROVIDER)}`,
    `model = ${q(defaultModel)}`,
    `model_catalog_json = ${q(catalogPath)}`,
    "",
    `[model_providers.${PROVIDER}]`,
    `name = "Meridian Router"`,
    `base_url = ${q(baseUrl)}`,
    `wire_api = "responses"`,
    `requires_openai_auth = false`,
    "",
    `[model_providers.${PROVIDER}.auth]`,
    `command = ${q(keyCommand)}`,
    `args = [${keyArgs.map(q).join(", ")}]`,
    "",
  ].join("\n");
}

/** The model a bare `--profile meridian` starts on: the failover role, not a single lane. */
export function defaultModel() {
  return "coder";
}

function main(argv) {
  const home = process.env.CODEX_HOME || path.join(os.homedir(), ".codex");
  const write = argv.includes("--write");
  const profilePath = path.join(home, `${PROVIDER}.config.toml`);
  const catalogPath = path.join(home, "meridian-models.json");
  const templateSrc = JSON.parse(fs.readFileSync(path.join(home, "models.json"), "utf8")).models?.[0];
  const pool = rolePool();
  const lanes = [...new Map(Object.values(pool.roles).flatMap((r) => r.candidates).filter((c) => c.enabled).map((c) => [c.id, c])).values()];
  const catalog = codexCatalog(templateSrc, [
    { id: defaultModel(), vendor: "failover", maxContextTokens: Math.min(...lanes.map((l) => l.maxContextTokens)) },
    ...lanes,
  ]);
  const secretLoad = path.join(os.homedir(), "Documents/code/estate-secrets/scripts/secret-load");
  const profile = profileToml({
    catalogPath,
    keyCommand: secretLoad,
    keyArgs: ["dev", KEY_NAME, KEY_NAME],
    defaultModel: defaultModel(),
  });
  const catalogText = JSON.stringify(catalog, null, 2) + "\n";
  console.log(JSON.stringify({ models: catalog.models.map((m) => m.slug), write, key_name: KEY_NAME }));
  if (!write) return 0;
  fs.writeFileSync(catalogPath, catalogText);
  fs.writeFileSync(profilePath, profile);
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.exit(main(process.argv.slice(2)));
